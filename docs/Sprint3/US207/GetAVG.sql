create FUNCTION GetAVG(id INTEGER,  y INTEGER) RETURN INTEGER
IS
AVGperManifest INTEGER;
BEGIN
        SELECT AVG(c)  INTO AVGperManifest
        FROM (SELECT IDCARGOMANIFEST, COUNT(*) AS c
        FROM MANIFESTCONTAINER WHERE IDCARGOMANIFEST IN (SELECT IDCARGOMANIFEST
        FROM CARGOMANIFEST WHERE EXTRACT(YEAR FROM ELABORATIONDATE ) = y AND (IDCARGOMANIFEST IN (SELECT IDCARGOMANIFESTLOAD
        FROM ARRIVALDEPARTURE WHERE IDTRIP IN (SELECT IDTRIP FROM CREW WHERE IDEMPLOYEE = id)) OR IDCARGOMANIFEST IN (SELECT IDCARGOMANIFESTUNLOAD
        FROM ARRIVALDEPARTURE WHERE IDTRIP IN (SELECT IDTRIP FROM CREW WHERE IDEMPLOYEE = id)))) GROUP BY IDCARGOMANIFEST);
        RETURN AVGperManifest;
END;