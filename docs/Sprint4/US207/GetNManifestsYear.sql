create FUNCTION GetNManifestsYear(id INTEGER,  y INTEGER) RETURN INTEGER
IS
nManifests INTEGER;
BEGIN
        SELECT  COUNT(*) INTO nManifests
        FROM CARGOMANIFEST WHERE EXTRACT(YEAR FROM ELABORATIONDATE ) = y AND (IDCARGOMANIFEST IN (SELECT IDCARGOMANIFESTLOAD
        FROM ARRIVALDEPARTURE WHERE IDTRIP IN (SELECT IDTRIP FROM CREW WHERE IDEMPLOYEE = ID)) OR IDCARGOMANIFEST IN (SELECT IDCARGOMANIFESTUNLOAD
        FROM ARRIVALDEPARTURE WHERE IDTRIP IN (SELECT IDTRIP FROM CREW WHERE IDEMPLOYEE = id)));

        RETURN nManifests;

END;